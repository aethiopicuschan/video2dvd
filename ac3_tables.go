// Constant tables of ATSC A/52:2018 (AC-3) that the encoder needs. The bit
// allocation tables must be bit-exact copies of the standard's: a decoder
// recomputes the allocation from the same tables, and any difference would
// make it read the mantissas with the wrong widths.

// ac3Bitrates lists the supported bitrates in bit/s. They are the A/52
// stereo rates that keep roughly 20 kHz of bandwidth; DVD-Video allows AC-3
// up to 448 kbit/s.
