// ac3MaskTab maps a transform bin to its bit allocation band (A/52 Table
// 7.12). It is derived from the band table rather than copied so that the two
// cannot disagree.
var ac3MaskTab = func() (table [256]int) {
	for band := range ac3BandStart {
		for bin := ac3BandStart[band]; bin < ac3BandStart[band]+ac3BandSize[band]; bin++ {
			table[bin] = band
		}
	}
	for bin := 253; bin < len(table); bin++ {
		table[bin] = len(ac3BandStart) - 1
	}
	return table
}()

